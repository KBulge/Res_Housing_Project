SELECT
    PARCL_ID,
    DATE,
    SINGLE_FAMILY,
    CONDO,
    TOWNHOUSE,
    OTHER,
    ALL_PROPERTIES,
    LOAD_TIMESTAMP,
    SOURCE

FROM RES_HOUSING.BRONZE.RAW_SF_HOUSING_STOCK

WHERE PARCL_ID IS NOT NULL
  AND DATE IS NOT NULL

  -- Counts cannot be negative
  AND SINGLE_FAMILY >= 0
  AND CONDO >= 0
  AND TOWNHOUSE >= 0
  AND OTHER >= 0
  AND ALL_PROPERTIES >= 0

  -- Component counts must reconcile
  AND SINGLE_FAMILY
      + CONDO
      + TOWNHOUSE
      + OTHER
      = ALL_PROPERTIES

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY PARCL_ID, DATE
    ORDER BY LOAD_TIMESTAMP DESC
) = 1;




