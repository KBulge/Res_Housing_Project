    PARCL_ID,
    DATE,
    ACQUISITIONS,
    DISPOSITIONS,
    NEW_LISTINGS_FOR_SALE,
    NEW_RENTAL_LISTINGS,
    TRANSFERS,
    PORTFOLIO_SIZE,
    LOAD_TIMESTAMP,
    SOURCE

FROM RES_HOUSING.BRONZE.RAW_SF_HOUSING_EVENTS

WHERE PARCL_ID IS NOT NULL
  AND DATE IS NOT NULL
  AND PORTFOLIO_SIZE IS NOT NULL

  -- Only expected portfolio categories
  AND PORTFOLIO_SIZE IN (
      'PORTFOLIO_2_TO_9',
      'PORTFOLIO_10_TO_99',
      'PORTFOLIO_100_TO_999',
      'PORTFOLIO_1000_PLUS'
  )

