  AND PCT_SF_HOUSING_STOCK_PORTFOLIO_10_TO_99 BETWEEN 0 AND 100
  AND PCT_SF_HOUSING_STOCK_PORTFOLIO_100_TO_999 BETWEEN 0 AND 100
  AND PCT_SF_HOUSING_STOCK_PORTFOLIO_1000_PLUS BETWEEN 0 AND 100
  AND PCT_SF_HOUSING_STOCK_ALL_PORTFOLIOS BETWEEN 0 AND 100

